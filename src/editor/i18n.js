/** @type {Record<string, string>} */

/** @type {Record<string, Record<string, string>>} 読み込んだ辞書（英語は使うときに読み込む） */
const messages = { ja };

/**
 * locale の表示に必要な辞書を読み込む（'ja' 以外は英語を読み込み、無いキーの代わりにも使う）
 * @param {string} locale
 * @returns {Promise<void>}
 */
export async function loadMessages(locale) {
  if (!needsMessages(locale)) return;
  const { en } = await importEnglish();
  messages.en = en;
}

/**
 * 辞書を読み込む必要があるか
 * @param {string} locale
 */
export function needsMessages(locale) {
  return locale !== 'ja' && !messages.en;
}

/**
 * @callback Translate
 * @param {string} key
 * @param {Record<string, string | number>} [params]
 * @returns {string}
 */

/**
 * @param {string} locale
 * @param {Record<string, string>} [overrides] 利用者による部分上書き
 * @returns {Translate}
 */
export function createTranslator(locale, overrides = {}) {
  return (key, params = {}) => {
    const message = overrides[key] ?? messages[locale]?.[key] ?? messages.en?.[key];
    if (message === undefined) return translate(locale, key, params, overrides);
    return message.replace(/\{(\w+)\}/g, (match, name) =>
      Object.hasOwn(params, name) ? String(params[name]) : match,
    );
  };
}
