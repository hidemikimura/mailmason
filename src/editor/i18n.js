/** @type {Record<string, Record<string, string>>} */
export const EDITOR_MESSAGES = { ja, en };

/**
 * @callback Translate
 * @param {string} key
 * @param {Record<string, string | number>} [params]
 * @returns {string}
 */

/**
 * @param {string} locale
 * @param {Record<string, string>} [overrides] 利用者による部分上書き
 * @returns {Translate}
 */
export function createTranslator(locale, overrides = {}) {
  return (key, params = {}) => {
    const message = overrides[key] ?? EDITOR_MESSAGES[locale]?.[key] ?? EDITOR_MESSAGES.en[key];
    if (message === undefined) return translate(locale, key, params, overrides);
    return message.replace(/\{(\w+)\}/g, (match, name) =>
      Object.hasOwn(params, name) ? String(params[name]) : match,
    );
  };
}
